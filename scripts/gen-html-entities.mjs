#!/usr/bin/env node
// Writes crates/svn-lint/src/html_entities.rs from the Svelte compiler's
// own table of named character references
// (.svelte-upstream/svelte/packages/svelte/src/compiler/phases/1-parse/utils/entities.js).
//
// The compiler builds one regular expression out of the table's keys in
// the order they are written, and the first alternative that matches
// wins, so the order is kept as it is.
//
//   node scripts/gen-html-entities.mjs
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const source = path.join(
	root,
	'.svelte-upstream/svelte/packages/svelte/src/compiler/phases/1-parse/utils/entities.js'
);
const { default: entities } = await import(pathToFileURL(source).href);

let out = `//! The named HTML character references the Svelte compiler decodes, in
//! the order of its own table (\`phases/1-parse/utils/entities.js\`).
//!
//! GENERATED by \`node scripts/gen-html-entities.mjs\`. Do not edit.

/// \`(name as written after the \`&\`, code point)\`. Names that end in
/// \`;\` are the regular form; the others are the legacy ones the HTML
/// parser also accepts without it.
pub(crate) const ENTITIES: &[(&str, u32)] = &[
`;
for (const [name, code] of Object.entries(entities)) {
	out += `    (${JSON.stringify(name)}, ${code}),\n`;
}
out += '];\n';
writeFileSync(path.join(root, 'crates/svn-lint/src/html_entities.rs'), out);
console.log(`wrote ${Object.keys(entities).length} entities`);
